"""Typed SDK structs from the reference SDK, only for what the client touches.

  python tools/sdkgen/gen_types.py

Roots: every class a sig in src/sdk/Sigs.json belongs to, every packet in the reference's mc/network/packet, and every
component the reference models. Their bases and the reference classes their members hold are generated too (one level).
A class the SDK already writes by hand is never generated (its header is left alone and used as is).

Each struct reproduces the reference's layout field by field: a member whose type maps to an SDK type keeps that type
(GameString for std::string, GameVector for std::vector, Vec3, Matrix, enums, other generated structs...),
anything else becomes aligned bytes of the same size. Every offset and the size are static_asserted.
Generated headers start with GENERATED and are the only files this tool overwrites.
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
import layout as L  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SDK = os.path.join(ROOT, 'src', 'sdk')
OUT = os.path.join(SDK, 'mc')
COMPONENTS = os.environ.get('COMPONENTS_REFERENCE')  # the component models of the current build
assert COMPONENTS, 'set COMPONENTS_REFERENCE to the component models'
GENERATED = '// GENERATED by tools/sdkgen/gen_types.py (do not edit; rerun the tool)'

PRIM = {'bool': ('bool', 1), 'char': ('char', 1), 'schar': ('int8_t', 1), 'uchar': ('uint8_t', 1), 'short': ('int16_t', 2),
        'ushort': ('uint16_t', 2), 'int': ('int32_t', 4), 'uint': ('uint32_t', 4), 'float': ('float', 4), 'double': ('double', 8),
        'int64': ('int64_t', 8), 'uint64': ('uint64_t', 8), 'size_t': ('size_t', 8), 'uint8_t': ('uint8_t', 1),
        'uint16_t': ('uint16_t', 2), 'uint32_t': ('uint32_t', 4), 'uint64_t': ('uint64_t', 8), 'int8_t': ('int8_t', 1),
        'int16_t': ('int16_t', 2), 'int32_t': ('int32_t', 4), 'int64_t': ('int64_t', 8)}
SDK_TYPES = {  # reference type -> (our type, size, include)
    'Vec2': ('Vec2', 8, 'sdk/mc/deps/core/math/Vec.h'), 'Vec3': ('Vec3', 12, 'sdk/mc/deps/core/math/Vec.h'),
    'glm::vec2': ('Vec2', 8, 'sdk/mc/deps/core/math/Vec.h'), 'glm::vec3': ('Vec3', 12, 'sdk/mc/deps/core/math/Vec.h'),
    'glm::vec4': ('Vec4', 16, 'sdk/mc/deps/core/math/Vec.h'), 'BlockPos': ('BlockPos', 12, 'sdk/mc/deps/core/math/BlockPos.h'),
    'mce::Color': ('mce::Color', 16, 'sdk/mc/deps/core/math/Color.h'), 'Matrix': ('Matrix', 64, 'sdk/mc/deps/core/math/Matrix.h'),
    'glm::mat4': ('Matrix', 64, 'sdk/mc/deps/core/math/Matrix.h'), 'HashedString': ('HashedString', 48, 'sdk/mc/deps/core/string/HashedString.h'),
    'std::string': ('GameString', 32, 'sdk/mc/deps/core/string/GameString.h'),
}
ENUM_SIZE = {'uchar': 1, 'schar': 1, 'char': 1, 'uint8_t': 1, 'int8_t': 1, 'ushort': 2, 'short': 2, 'uint16_t': 2, 'int16_t': 2,
             'int': 4, 'uint': 4, 'uint32_t': 4, 'int32_t': 4, 'int64': 8, 'uint64': 8, 'uint64_t': 8, 'int64_t': 8}
HAND_BASES = {'Packet': (0x30, 8, 'sdk/mc/network/Packet.h')}


def hand_written():
    names = {}
    for dp, _, fns in os.walk(SDK):
        for fn in fns:
            if not fn.endswith('.h'):
                continue
            path = os.path.join(dp, fn)
            src = open(path, encoding='utf-8', errors='replace').read()
            if src.startswith(GENERATED):
                continue
            for m in re.finditer(r'^(?:struct|class)\s+(\w+)\s*[:{]', src, re.M):
                names[m.group(1)] = os.path.relpath(path, os.path.join(ROOT, 'src')).replace('\\', '/')
    return names


HAND = hand_written()


def reference_rel(path):
    for tree in ('src-client', 'src', 'src-server'):
        base = os.path.join(L.REFERENCE, tree) + os.sep
        if path.startswith(base):
            return os.path.relpath(path, base).replace('\\', '/')
    return None


def enum_of(name):
    path = L.find_header(name)
    if not path:
        return None
    src = open(path, encoding='utf-8').read()
    m = re.search(r'^enum class\s+%s\s*(?::\s*([\w:]+))?\s*\{(.*?)\};' % re.escape(name), src, re.M | re.S)
    if not m:
        return None
    return (m.group(1) or 'int', m.group(2), path)


def simple(t):
    t = t.strip()
    t = re.sub(r'\bconst\b', '', t).strip()
    return t[2:] if t.startswith('::') else t


class Gen:
    def __init__(self):
        self.classes = {}  # name -> Layout
        self.enums = {}    # name -> (underlying, body, path)

    def want(self, name, depth):
        if name in self.classes or name in HAND or name in PRIM or name in SDK_TYPES:
            return
        lay = L.layout(name)
        if not lay.known or not lay.path:
            return
        if not lay.members and not lay.virtuals and lay.size == 0 and not name.endswith('Component'):
            return
        self.classes[name] = lay
        for b in lay.bases:
            bn = re.sub(r'<.*', '', b).strip().split('::')[-1]
            pay = re.search(r'PayloadPacket<\s*::?(\w+)\s*>', b)
            if pay:
                self.want(pay.group(1), depth)
            elif bn not in HAND_BASES:
                self.want(bn, depth)
        if depth > 0:
            for _, _, _, _, t in lay.members:
                for ident in re.findall(r'::(\w+)', t):
                    if ident[0].isupper():
                        self.want(ident, depth - 1)

    def map_type(self, t, size, deps, fwd):
        s = simple(t)
        if s in PRIM and PRIM[s][1] == size:
            return PRIM[s][0]
        if s in SDK_TYPES and SDK_TYPES[s][1] == size:
            deps.add(SDK_TYPES[s][2])
            return SDK_TYPES[s][0]
        if s.endswith('*') and size == 8:
            inner = simple(s[:-1])
            if inner == 'void':
                return 'void*'
            if re.fullmatch(r'\w+', inner):
                if inner in PRIM:
                    return PRIM[inner][0] + '*'
                fwd.add(inner)
                return inner + '*'
            return 'void*'
        m = re.fullmatch(r'std::unique_ptr<\s*::(\w+)\s*>', s)
        if m and size == 8:
            fwd.add(m.group(1))
            return m.group(1) + '*'
        m = re.fullmatch(r'std::(shared_ptr|weak_ptr)<\s*::(\w+)\s*>', s)
        if m and size == 16:
            fwd.add(m.group(2))
            deps.add('sdk/mc/deps/core/GameSharedPtr.h')
            return 'GameSharedPtr<%s>' % m.group(2)
        m = re.fullmatch(r'std::vector<\s*(.+)\s*>', s)
        if m and size == 24:
            deps.add('sdk/mc/deps/ecs/EnttStorage.h')
            el = simple(m.group(1))
            if el in PRIM:
                return 'GameVector<%s>' % PRIM[el][0]
            if el in SDK_TYPES:
                deps.add(SDK_TYPES[el][2])
                return 'GameVector<%s>' % SDK_TYPES[el][0]
            if re.fullmatch(r'\w+', el) and el in self.classes and self.classes[el].size:
                self.dep_on(el, deps, fwd)
                return 'GameVector<%s>' % el
            return 'GameVector<std::byte>'
        if re.fullmatch(r'\w+', s):
            e = self.enum(s)
            if e and ENUM_SIZE.get(simple(e[0]), 4) == size:
                deps.add(self.header_of(s))
                return s
            if s in self.classes and self.classes[s].size == size:
                self.dep_on(s, deps, fwd)
                return s
        return None

    def enum(self, name):
        if name in self.enums:
            return self.enums[name]
        e = enum_of(name)
        if e:
            self.enums[name] = e
        return e

    def dep_on(self, name, deps, fwd):
        deps.add(HAND[name] if name in HAND else self.header_of(name))

    def header_of(self, name):
        path = L.find_header(name) if name not in self.enums else self.enums[name][2]
        rel = reference_rel(path)
        return 'sdk/' + rel

    def emit_enum(self, name):
        under, body, path = self.enums[name]
        under = {'uchar': 'uint8_t', 'schar': 'int8_t', 'ushort': 'uint16_t', 'short': 'int16_t', 'uint': 'uint32_t', 'int': 'int32_t',
                 'int64': 'int64_t', 'uint64': 'uint64_t'}.get(simple(under), simple(under))
        body = '\n'.join(l for l in body.split('\n') if l.strip() and not l.strip().startswith('//'))
        if re.search(r'::\w', body):
            body = re.sub(r'=\s*[^,\n]*::[^,\n]*', '', body)  # values that reference other types: keep the order only
        out = os.path.join(ROOT, 'src', self.header_of(name))
        if self.is_hand_file(out):
            return
        os.makedirs(os.path.dirname(out), exist_ok=True)
        open(out, 'w', encoding='utf-8', newline='\n').write('%s\n#pragma once\n#include <cstdint>\n\nenum class %s : %s {\n%s\n};\n' % (GENERATED, name, under, body))

    @staticmethod
    def is_hand_file(path):
        return os.path.exists(path) and not open(path, encoding='utf-8', errors='replace').read().startswith(GENERATED)

    def emit_class(self, name, hashes):
        lay = self.classes[name]
        deps, fwd = set(), set()
        lines, asserts = [], []
        inherit = None
        cursor = 0
        npad = [0]

        def pad_to(off):
            nonlocal cursor
            if off > cursor:
                lines.append('    std::byte mPad%d[0x%X];' % (npad[0], off - cursor))
                npad[0] += 1
                cursor = off
            assert off == cursor, (name, off, cursor)

        if lay.own_vptr:
            lines.append('    void* mVtable;')
            cursor = 8
        for i, b in enumerate(lay.bases):
            bn = re.sub(r'<.*', '', b).strip().split('::')[-1]
            if bn in HAND_BASES:
                size, align, inc = HAND_BASES[bn]
            else:
                bl = L.layout(bn)
                if not (bl.known and bl.size):
                    continue
                size, align, inc = bl.size, bl.align, (self.header_of(bn) if bn in self.classes else None)
            off = L.alignup(cursor, align)
            if i == 0 and inc and cursor == 0:
                deps.add(inc)
                inherit = bn
                cursor = size
            else:
                pad_to(off)
                if inc:
                    deps.add(inc)
                    lines.append('    %s mBase%s;' % (bn, bn))
                else:
                    lines.append('    std::byte mBase%s[0x%X];' % (bn, size))
                cursor += size
        if lay.has_vptr and cursor == 0:
            lines.append('    void* mVtable;')
            cursor = 8
        for n, off, size, align, t in lay.members:
            pad_to(off)
            ty = self.map_type(t, size, deps, fwd)
            if ty:
                lines.append('    %s %s;' % (ty, n))
            else:
                lines.append('    std::byte %s[0x%X]; // %s' % (n, size, re.sub(r'\s+', ' ', t)))
            cursor += size
            asserts.append('static_assert(offsetof(%s, %s) == 0x%X);' % (name, n, off))
        if lay.size:
            pad_to(lay.size)
            asserts.append('static_assert(sizeof(%s) == 0x%X);' % (name, lay.size))
        h = hashes.get(name)
        head = '    static constexpr uint32_t enttHash = 0x%08X;\n' % h if h else ''
        decl = '#pragma pack(push, 1)\nstruct %s%s {\n%s%s\n};\n#pragma pack(pop)\n' % (name, (' : ' + inherit) if inherit else '', head, '\n'.join(lines))
        own = self.header_of(name)
        deps.discard(own)
        fwd -= {name}
        text = GENERATED + '\n#pragma once\n#include <cstddef>\n#include <cstdint>\n'
        text += ''.join('#include "%s"\n' % d for d in sorted(deps))
        text += ''.join('struct %s;\n' % f for f in sorted(fwd) if f not in self.enums)
        text += '\n' + decl + '\n'.join(asserts) + '\n'
        out = os.path.join(ROOT, 'src', own)
        if self.is_hand_file(out):
            print('skip (hand-written file at the same path):', own)
            return
        os.makedirs(os.path.dirname(out), exist_ok=True)
        open(out, 'w', encoding='utf-8', newline='\n').write(text)


def sig_classes():
    def leaves(node, path, out):
        if 'sigs' in node:
            if path[0] == 'mc':
                out.add(path[-2])
            return
        for k, v in node.items():
            leaves(v, path + [k], out)
    out = set()
    leaves(json.load(open(os.path.join(ROOT, 'src', 'sdk', 'Sigs.json'))), [], out)
    return out


def packet_classes():
    d = os.path.join(L.REFERENCE, 'src', 'mc', 'network', 'packet')
    return {fn[:-2] for fn in os.listdir(d) if fn.endswith('Packet.h')}


def reference_components():
    names, hashes = set(), {}
    for fn in os.listdir(COMPONENTS):
        src = open(os.path.join(COMPONENTS, fn), encoding='utf-8', errors='replace').read()
        names |= set(re.findall(r'^\s*(?:struct|class)\s+(\w+Component)\b', src, re.M))
        for h, n in re.findall(r'\{\s*0x([0-9A-Fa-f]+)\s*,\s*"(?:class|struct)\s+(\w+)"\s*\}', src):
            hashes[n] = int(h, 16)
    # The type hashes of the current build are the current build's table (ENTT_HASH__(Name, 0xHASH)); it wins over any older tables.
    table = os.path.normpath(os.path.join(COMPONENTS, '..', '..', '..', 'EnttHashs.hpp'))
    for n, h in re.findall(r'ENTT_HASH__\((\w+),\s*0x([0-9A-Fa-f]+)u?\)', open(table, encoding='utf-8', errors='replace').read()):
        hashes[n] = int(h, 16)
    return names, hashes


def main():
    comps, hashes = reference_components()
    gen = Gen()
    for c in sorted(sig_classes()):
        gen.want(c, 1)
    for c in sorted(packet_classes()):
        gen.want(c, 1)
    for c in sorted(comps):
        gen.want(c, 1)
    # removed generated files are not left behind
    for dp, _, fns in os.walk(OUT):
        for fn in fns:
            p = os.path.join(dp, fn)
            if fn.endswith('.h') and open(p, encoding='utf-8', errors='replace').read().startswith(GENERATED):
                os.remove(p)
    for name in sorted(gen.classes):
        gen.emit_class(name, hashes)
    for name in sorted(gen.enums):
        gen.emit_enum(name)
    check = os.path.join(SDK, 'GeneratedCheck.cpp')
    heads = []
    for dp, _, fns in os.walk(OUT):
        for fn in fns:
            p = os.path.join(dp, fn)
            if fn.endswith('.h') and open(p, encoding='utf-8', errors='replace').read().startswith(GENERATED):
                heads.append(os.path.relpath(p, os.path.join(ROOT, 'src')).replace(os.sep, '/'))
    open(check, 'w', encoding='utf-8', newline=chr(10)).write(GENERATED + chr(10) + '// Compiles every generated header once, so every layout assert is checked by the build.' + chr(10) + ''.join('#include "%s"' % h + chr(10) for h in sorted(heads)))
    print('%d structs, %d enums' % (len(gen.classes), len(gen.enums)))


if __name__ == '__main__':
    main()
