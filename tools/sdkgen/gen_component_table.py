"""Lists every ECS component the SDK knows (a struct with `static constexpr uint32_t enttHash`) in
src/sdk/mc/deps/ecs/ComponentTable.h, so tools like the DebugUI can probe them generically.

  python tools/sdkgen/gen_component_table.py
"""
# Parked: its output (src/sdk/mc/deps/ecs/ComponentTable.h) is not tracked until DebugUI consumes it.
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SDK = os.path.join(ROOT, 'src', 'sdk')
pat = re.compile(r'struct\s+(\w+)\s*(?::[^{]*)?\{(?:(?!\n\};).)*?static constexpr uint32_t enttHash\s*=\s*(0x[0-9A-Fa-f]+)', re.S)
found = {}
for d, _, fs in os.walk(SDK):
    for f in fs:
        if not f.endswith('.h'):
            continue
        txt = open(os.path.join(d, f), encoding='utf-8', errors='replace').read()
        for m in pat.finditer(txt):
            found[m.group(1)] = int(m.group(2), 16)
rows = ''.join('    {"%s", 0x%08Xu},\n' % (n, h) for n, h in sorted(found.items()))
out = os.path.join(SDK, 'mc', 'deps', 'ecs', 'ComponentTable.h')
open(out, 'w', encoding='utf-8', newline='\n').write(
    '// GENERATED by tools/sdkgen/gen_component_table.py (do not edit; rerun the tool)\n#pragma once\n#include <cstdint>\n\n'
    '// Every ECS component struct of the SDK with its entt type hash.\nstruct ComponentInfo {\n    const char* name;\n    uint32_t hash;\n};\n\n'
    'inline constexpr ComponentInfo kComponentTable[] = {\n' + rows + '};\n')
print('%d components -> %s' % (len(found), out))
